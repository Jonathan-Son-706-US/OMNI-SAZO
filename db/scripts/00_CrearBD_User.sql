IF DB_ID('OMNISAZO') IS NULL CREATE DATABASE OMNISAZO;
GO
IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = '$(APP_USER)')
    CREATE LOGIN [$(APP_USER)] WITH PASSWORD = '$(APP_PASS)';
GO
USE OMNISAZO;
GO
IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = '$(APP_USER)')
    CREATE USER [$(APP_USER)] FOR LOGIN [$(APP_USER)];
ALTER ROLE db_owner ADD MEMBER [$(APP_USER)];
GO
ALTER LOGIN [$(APP_USER)] WITH PASSWORD = '$(APP_PASS)';
GO